function europolis_board_size(): int
{
    return count(europolis_tiles());
}

function europolis_jail_index(): int
{
    return 7;
}

function europolis_building_progression(): array
{
    return ['1 casa', '2 case', '3 case', 'Hotel'];
}

function europolis_upgrade_percentages(): array
{
    return [0 => 0, 1 => 5, 2 => 15, 3 => 20, 4 => 40];
}

function europolis_upgrade_label(int $level): string
{
    return [0 => 'Fara upgrade', 1 => '1 casa', 2 => '2 case', 3 => '3 case', 4 => 'Hotel'][$level] ?? 'Fara upgrade';
}

function europolis_build_cost(array $tile, int $nextLevel): int
{
    $price = (int)($tile['price'] ?? 0);
    $nextLevel = max(1, min(4, $nextLevel));

    if ($nextLevel === 4) {
        return (int)ceil($price * 2.5);
    }

    return (int)ceil($price * 0.6);
}

function europolis_calculate_rent(array $tile, int $upgradeLevel = 0): int
{
    $price = (int)($tile['price'] ?? 0);
    $minimumRent = $price > 0 ? (int)ceil($price * 0.3) : 0;
    $configuredRent = (int)($tile['rent'] ?? 0);
    $baseRent = max($minimumRent, $configuredRent);
    $upgradeLevel = max(0, min(4, $upgradeLevel));
    $percent = europolis_upgrade_percentages()[$upgradeLevel] ?? 0;

    return (int)round($baseRent * (1 + ($percent / 100)));
}

function europolis_property_groups(): array
{
    $groups = [];
    foreach (europolis_tiles() as $tile) {
        if ($tile['type'] !== 'property') {
            continue;
        }
        $groups[$tile['color']][] = $tile['name'];
    }

    return $groups;
}

function europolis_group_members(?string $color): array
{
    if ($color === null) {
        return [];
    }

    return europolis_property_groups()[$color] ?? [];
}

function europolis_get_tile(int $index): array
{
    $tiles = europolis_tiles();
    return $tiles[$index] ?? ['index' => $index, 'type' => 'unknown', 'name' => 'Necunoscut', 'price' => null, 'rent' => null, 'color' => null];
}
